package io.github.mahiron_hq.mahiroute.bootstrap

import android.content.ContentValues
import android.content.Context
import android.os.Environment
import android.provider.MediaStore
import androidx.core.content.edit
import java.io.File
import java.io.IOException
import java.net.InetAddress
import java.net.InetSocketAddress
import java.net.Socket
import java.security.SecureRandom

/**
 * The alternative to wireless debugging for phones that cannot use it, for example because they
 * share their connection over Wi-Fi: the app prepares a script on the phone and the user runs it
 * through `adb` from a computer, most easily with the Windows launcher the app can save.
 */
object PcStart {
    const val PORT = 41_999
    private const val PREFS = "pc_start"
    private const val KEY_TOKEN = "token"
    private const val SCRIPT_NAME = "start-helper.sh"
    private const val LAUNCHER_NAME = "MahiRoute-start.bat"
    private const val STATE_FILE = "/data/local/tmp/mahiroute-state.json"
    private const val LOG_FILE = "/data/local/tmp/mahiroute-helper.log"
    private const val HELPER_CLASS = "io.github.mahiron_hq.mahiroute.helper.HelperMain"
    private const val PROBE_TIMEOUT_MS = 300

    /** What the interface shows and what a connection needs. */
    data class Info(val command: String, val port: Int, val token: String)

    /** Writes the start script and returns the one-line command that runs it. */
    fun prepare(context: Context): Info {
        val token = token(context)
        val directory = context.getExternalFilesDir(null) ?: context.filesDir
        val script = File(directory, SCRIPT_NAME)
        script.writeText(script(context.packageName, token))
        return Info("adb shell sh ${script.absolutePath}", PORT, token)
    }

    /** Points the engine at the helper the script starts and remembers it for later launches. */
    fun connect(context: Context, info: Info) {
        HelperEndpointStore.save(context, info.port, info.token)
        io.github.mahiron_hq.mahiroute.core.EngineHost.connect(info.port, info.token)
    }

    /** Whether something accepts connections on the helper's fixed port, as a started script's helper does. */
    fun helperListening(): Boolean =
        try {
            Socket().use { it.connect(InetSocketAddress(InetAddress.getLoopbackAddress(), PORT), PROBE_TIMEOUT_MS) }
            true
        } catch (_: IOException) {
            false
        }

    /** Copies the Windows launcher into the Downloads folder, replacing an earlier copy; false on failure. */
    fun saveWindowsLauncher(context: Context): Boolean {
        val resolver = context.contentResolver
        val downloads = MediaStore.Downloads.EXTERNAL_CONTENT_URI
        // The app owns the earlier copy, so it may remove it; otherwise the system would rename the new one.
        resolver.delete(
            downloads,
            "${MediaStore.MediaColumns.DISPLAY_NAME}=? AND ${MediaStore.MediaColumns.OWNER_PACKAGE_NAME}=?",
            arrayOf(LAUNCHER_NAME, context.packageName),
        )
        val values =
            ContentValues().apply {
                put(MediaStore.MediaColumns.DISPLAY_NAME, LAUNCHER_NAME)
                put(MediaStore.MediaColumns.MIME_TYPE, "application/octet-stream")
                put(MediaStore.MediaColumns.RELATIVE_PATH, Environment.DIRECTORY_DOWNLOADS)
            }
        val target = resolver.insert(downloads, values) ?: return false
        return try {
            val out = resolver.openOutputStream(target) ?: throw IOException("no output stream")
            out.use { stream -> context.assets.open(LAUNCHER_NAME).use { it.copyTo(stream) } }
            true
        } catch (_: IOException) {
            resolver.delete(target, null, null)
            false
        }
    }

    private fun token(context: Context): String {
        val prefs = context.getSharedPreferences(PREFS, Context.MODE_PRIVATE)
        prefs.getString(KEY_TOKEN, null)?.let { return it }
        val bytes = ByteArray(TOKEN_BYTES).also { SecureRandom().nextBytes(it) }
        val fresh = bytes.joinToString("") { "%02x".format(it) }
        prefs.edit { putString(KEY_TOKEN, fresh) }
        return fresh
    }

    private fun script(packageName: String, token: String): String =
        """
        #!/system/bin/sh
        # Starts the MahiRoute helper with shell rights. Generated by the app.
        pm grant $packageName android.permission.WRITE_SECURE_SETTINGS 2>/dev/null
        APK=${'$'}(pm path $packageName | head -n 1 | cut -d: -f2)
        kill ${'$'}(pidof mahiroute-helper) 2>/dev/null
        sleep 0.3
        CLASSPATH=${'$'}APK nohup app_process /system/bin --nice-name=mahiroute-helper $HELPER_CLASS \
          --token $token --port $PORT --state $STATE_FILE > $LOG_FILE 2>&1 < /dev/null &
        sleep 1
        echo "MahiRoute helper started"
        """.trimIndent() + "\n"

    private const val TOKEN_BYTES = 16
}
